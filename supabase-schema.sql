-- Optional anti-delete audit log table. Keep RLS enabled and do not expose service-role key to clients.
create table if not exists public.bot_audit_events (
  id bigint generated by default as identity primary key,
  account_id text not null,
  event_type text not null,
  chat_jid text,
  sender_jid text,
  message_type text,
  message_text text,
  created_at timestamptz not null default now()
);
alter table public.bot_audit_events enable row level security;
